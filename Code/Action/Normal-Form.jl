@doc raw"""
    is_passive(
        equations::AbstractVector{<:P},
        multiplicative::AbstractVector{<:BitVector};
        info::Bool=false,
        missing::Bool=false
    ) where {P<:ActionPolyRingElem}
    is_passive(
        equations::AbstractVector{<:P};
        info::Bool=false,
        missing::Bool=false
    ) where {P<:ActionPolyRingElem}
    is_passive(system::AbstractActionSystem; kwargs...)
    is_passive(system::AbstractActionSystem, multiplicative::AbstractVector{<:BitVector}; kwargs...)

Test passivity of a Janet-complete vector of difference or differential equations.
Reduce each elementary non-multiplicative prolongation with the same procedure as `normal_form`:
return `true` when every resulting `nf` is zero.
Reuse one normal-form cache for the unchanged equation basis throughout the test.
Compute multiplicative variables when they are omitted.

Check the algebraic regularity conditions separately when using passivity to
certify a simple differential system. For an `AbstractActionSystem`, inspect
only its equations; do not use its inequations in this test.

Set `info=true` to print the first nonzero remainder.
Set `missing=true` to return `(false, remainder, equation_index, action_index)` on failure;
otherwise return `false`. Raise an error if the equations are not Janet complete.

    # Examples

    ```jldoctest
    julia> R, (y2, y1) = difference_polynomial_ring(QQ, [:y2, :y1], 2; partition=[[1, 1]], index_ordering_name = :deglex);
    julia> f_1 = y2[1,0]-y1;
    julia> f_2 = y2-y1;
    julia> f_3 = y1[1,0]-y1;
    julia> F = [f_1, f_2, f_3];
    julia> is_passive(F)
    true

    julia> R, (y2, y1) = difference_polynomial_ring(QQ, [:y2, :y1], 2; partition=[[1, 1]], index_ordering_name = :deglex);
    julia> f_1 = y1[0,1]^2+1;
    julia> f_2 = y1[2,0]+y2[0,1];
    julia> f_3 = y1[0,1]*y2[0,2];
    julia> f_4 = y1[1,1]^2-y1[1,0]^4;
    julia> F = [f_1, f_2, f_3, f_4];
    julia> is_passive(F; info=true, missing=true)
    -y1[0,1]*y2[0,1]^4 is the nonzero Janet normal form of the action polynomial in position 4 after applying the elementary action [1, 0]
    (false, -y1[0,1]*y2[0,1]^4, 4, 1)

    julia> R, u = differential_polynomial_ring(QQ, :u, 2);
    julia> is_passive([u[1, 0]])
    true

    julia> R, (u, v, w) = differential_polynomial_ring(QQ, [:u, :v, :w], 2; index_ordering_name=:deglex);
    julia> E = [u[1,0] - v, u[0,1] - w];
    julia> is_passive(E; info=true, missing=true)
    -w[1,0] + v[0,1] is the nonzero Janet normal form of the action polynomial in position 2 after applying the elementary action [1, 0]
    (false, -w[1,0] + v[0,1], 2, 1)

    julia> R, (u, a) = differential_polynomial_ring(QQ, [:u, :a], 1; index_ordering_name=:deglex);
    julia> F = [a, a*u^2, apply_action(a*u^2, 1) + 1];
    julia> is_janet_complete(F)
    true
    julia> normal_form(apply_action(F[2], 1), F)
    (nf = -1, multiplier = 1)
    julia> is_passive(F; missing=true)
    (false, -1, 2, 1)
    ```
"""
function is_passive(
    equations::AbstractVector{<:P},
    multiplicative::AbstractVector{<:BitVector};
    info::Bool=false,
    missing::Bool=false
 ) where {P<:ActionPolyRingElem}
    __require_same_parent(equations)
    equations = collect(P, equations)
    any(is_constant, equations) && error("The action polynomials defining the equations must be nonconstant")
    data = __action_janet_data(equations, multiplicative)
    __is_janet_complete(data) || error(
            "The vector of action polynomials defining the equations " *
            "must be Janet complete",
        )
    return __is_passive(data; info, missing)
end

function is_passive(
    equations::AbstractVector{<:P};
    info::Bool=false,
    missing::Bool=false
 ) where {P<:ActionPolyRingElem}
    data = __normal_form_data(equations)
    return __is_passive(data; info, missing)
end

# Read the owned equations; detach any polynomial returned with missing=true.
is_passive(system::AbstractActionSystem; kwargs...) = deepcopy(is_passive(first(__action_read_system(system)); kwargs...))
is_passive(system::AbstractActionSystem, multiplicative::AbstractVector{<:BitVector}; kwargs...) =
    deepcopy(is_passive(first(__action_read_system(system)), multiplicative; kwargs...))

"""
Internal passivity test for a Janet-complete system represented by cached data.\
Reduce each elementary non-multiplicative prolongation using `__normal_form_cached`
and return `true` exactly when all resulting normal forms are zero, consistently
with the public `normal_form` procedure. Share one cache across prolongations
of the unchanged basis, including their recursive coefficient reductions.
Assume the caller has checked Janet completeness. Leave algebraic simplicity
and the nonvanishing of reducer initials to separate checks; see `is_passive`.

If `info` is true, a nonzero normal form witnessing non-passivity is printed,
together with the position of the polynomial in the vector and the non-multiplicative action applied to obtain it.
If `missing` is true, that obstruction is returned together with `false`.
"""
function __is_passive(
    data::__ActionJanetData{P};
    info::Bool=false,
    missing::Bool=false
 ) where {P<:ActionPolyRingElem}
    isempty(data.equations) && return true
    cache = Dict{P,Tuple{P,P}}()
    # Newly introduced obstructions are appended: inspect recent equations first.
    for equation_index in reverse(eachindex(data.equations))
        equation = data.equations[equation_index]
        multiplicative = data.multiplicative_variables[equation_index]
        for action_index in eachindex(multiplicative)
            multiplicative[action_index] && continue
            action = zeros(Int, length(multiplicative))
            action[action_index] = 1
            prolongation = apply_action(equation, action)
            normal_form_result = __normal_form_cached(prolongation, data, cache)
            obstruction = normal_form_result.nf
            is_zero(obstruction) && continue
            if info
                println(
                    "$obstruction is the nonzero Janet normal form of " *
                    "the action polynomial in position " *
                    "$equation_index after applying the " *
                    "elementary action $action",
                )
            end
            return missing ? (false, obstruction, equation_index, action_index) : false
        end
    end
    return true
end

# Fast path used specifically for recursive coefficient normal forms.
# If a coefficient contains no Janet-reducible variable at all, its normal form is
# already the coefficient itself and the pseudo-reduction multiplier is one.
# This avoids recursively decomposing an irreducible coefficient into its own univariate coefficients.
function __normal_form_coefficient_cached(
    p::P,
    data::__ActionJanetData{P},
    cache::Dict{P,Tuple{P,P}},
    certificate_cache::Union{Nothing,Dict{P,__NormalFormCertificate{P}}}=nothing,
    term_cache::Union{Nothing,Dict{P,Vector{Tuple{P,Vector{Int64},P}}}}=nothing,
) where {P<:ActionPolyRingElem}
    cached = get(cache, p, nothing)
    if cached !== nothing && (term_cache === nothing || haskey(term_cache, p))
        return (
            nf=cached[1],
            multiplier=cached[2],
        )
    end
    R = __require_same_parent(p, data.equations)
    if is_constant(p) ||
       __is_janet_reducible(p, data) === false
        result = (nf=p, multiplier=R(1))
        cache[p] = (result.nf, result.multiplier)
        term_cache === nothing || (term_cache[p] = Tuple{P,Vector{Int64},P}[])
        return result
    end
    return __normal_form_cached(p, data, cache, certificate_cache, term_cache)
end

# Extend one exponent vector in place instead of allocating vcat/fill temporaries in term builders.
function __action_pad_exponent_vector!(exponent::Vector{Int}, n_variables::Int)
    old_length = length(exponent)
    if old_length < n_variables
        resize!(exponent, n_variables)
        for i in (old_length + 1):n_variables
            exponent[i] = 0
        end
    end
    return exponent
end

# Extract coefficients in the universal ring's insertion order, independently
# of the action ranking. Read coefficient/exponent pairs without constructing
# a polynomial for every term or removing powers by polynomial division.
# Assume v is a jet variable, supplied by leader or vars at the internal call sites.
function __action_univariate_coefficients_by_terms(p::P, v::P) where {P<:ActionPolyRingElem}
    R = __require_same_parent(p, v)
    variable_index = var_index(Oscar.data(v))
    raw = Oscar.data(p)
    polynomial_degree = iszero(p) ? -1 : degree(raw, variable_index)
    return __action_univariate_coefficients_by_terms(p, R, variable_index, polynomial_degree)
end

# Reuse the validated parent, variable index and degree when the caller already has them.
function __action_univariate_coefficients_by_terms(
    p::P,
    R,
    variable_index::Int,
    polynomial_degree::Int
) where {P<:ActionPolyRingElem}
    universal_ring = base_ring(R)
    n_variables = ngens(universal_ring)
    raw = Oscar.data(p)
    contexts = [MPolyBuildCtx(universal_ring) for _ in 0:polynomial_degree]
    for (c, exponent) in zip(coefficients(raw), Oscar.AbstractAlgebra.exponent_vectors(raw))
        __action_pad_exponent_vector!(exponent, n_variables)
        power = exponent[variable_index]
        exponent[variable_index] = 0
        push_term!(contexts[power + 1], c, exponent)
    end
    return P[R(finish(context)) for context in contexts]
end

