@doc raw"""
    normal_form_terms(
        p::P,
        S::AbstractVector{<:P};
        print_output::Bool=false
    ) where {P<:ActionPolyRingElem}
    normal_form_terms(
        p::ActionPolyRingElem,
        system::AbstractActionSystem;
        kwargs...
    )

Work in a difference or differential polynomial ring with a fixed ranking.
Let `S` be a Janet complete set.
Return `(q, terms, r)`, where `r` is the Janet normal form of `p` modulo `S`,
`q` is its multiplier, and each tuple `(c, alpha, f)` records an admissible prolongation of an
original equation `f` in `S`. The returned values satisfy the exact identity

    q * p - r == sum(c*apply_action(f, alpha) for (c, alpha, f) in terms)

Record all contributions to the identity, including those from coefficients
whose normal form is zero.

Set `print_output=true` to print the multiplier, terms, and remainder without
changing the returned tuple.
Also accept an `AbstractActionSystem` in place of `S`.

    # Examples

    ```jldoctest
    julia> R, (y2, y1) = difference_polynomial_ring(QQ, [:y2, :y1], 2; partition=[[1, 1]], index_ordering_name = :deglex);
    julia> f_1 = y2*y1^2*y1[0,1]-5;
    julia> f_2 = y1*y2^2-25;
    julia> f_3 = y1[1,0]-1;
    julia> f_4 = y2[1,0]-5;
    julia> F = [f_1,f_2,f_3,f_4];
    julia> q = apply_action(F[1],[0,1]);
    julia> pr = normal_form(q, F)
    (nf = 0, multiplier = 1)
    julia> S = normal_form_terms(q, F)
    (1, Tuple{DifferencePolyRingElem{QQFieldElem}, Vector{Int64}, DifferencePolyRingElem{QQFieldElem}}[(1, [0, 1], y2[0,0]*y1[0,0]^2*y1[0,1] - 5)], 0)
    julia> S[1] == pr.multiplier
    true
    julia> S[3] == pr.nf
    true
    julia> pr.multiplier * q- pr.nf == sum([a*apply_action(c,b) for (a,b,c) in S[2]])
    true

    julia> R, (y2, y1) = difference_polynomial_ring(QQ, [:y2, :y1], 2; partition=[[1, 1]], index_ordering_name = :deglex);
    julia> f_1 = y1[0,1]^2+1;
    julia> f_2 = y1[2,0]+y2[0,1];
    julia> f_3 = y1[0,1]*y2[0,2];
    julia> f_4 = y1[1,1]^2-y1[1,0]^4;
    julia> F = [f_1, f_2, f_3, f_4];
    julia> q = y2[1,1]*y2[0,3]-y1[2,0];
    julia> pr = normal_form(q, F)
    (nf = y2[0,1]*y1[0,2], multiplier = y1[0,2])
    julia> S = normal_form_terms(q, F);
    julia> S[1] == pr.multiplier
    true
    julia> S[3] == pr.nf
    true
    julia> pr.multiplier * q- pr.nf == sum([a*apply_action(c,b) for (a,b,c) in S[2]])
    true

    julia> R, y = difference_polynomial_ring(QQ,:y,1);
    julia> f_1 = y*y[2]-1-y[1];
    julia> F=[f_1];
    julia> q = y[5]-y;
    julia> pr = normal_form(q, F)
    (nf = 0, multiplier = y[2]*y[1]*y[3])
    julia> S = normal_form_terms(q, F);
    julia> S[1] == pr.multiplier
    true
    julia> S[3] == pr.nf
    true
    julia> pr.multiplier * q- pr.nf == sum([a*apply_action(c,b) for (a,b,c) in S[2]])
    true
    ```
"""
function normal_form_terms(
    p::P,
    S::AbstractVector{<:P};
    print_output::Bool=false
) where {P<:ActionPolyRingElem}
    __require_same_parent(p, S)
    nf_data = __normal_form_data(S)
    r, q, raw_terms = __normal_form_recorded(p, nf_data)
    terms = __normal_form_group_terms(raw_terms, nf_data)
    print_output && __print_normal_form_terms(q, terms, r)
    return q, terms, r
end

function normal_form_terms(p::ActionPolyRingElem, system::AbstractActionSystem; kwargs...)
    __require_parent(system.ring, p)
    return normal_form_terms(p, system.equations; kwargs...)
end

"""
Run the same reduction as `normal_form`, additionally caching complete identities
for recursive subproblems. Return `(remainder, multiplier, terms)`.
Use a fresh fixed-basis cache and record every exact or pseudo-reduction step;
leave cross-basis zero certificates unused because they do not store these terms.
"""
function __normal_form_recorded(
    p::P,
    data::__ActionJanetData{P}
) where {P<:ActionPolyRingElem}
    cache = Dict{P,Tuple{P,P}}()
    term_cache = Dict{P,Vector{Tuple{P,Vector{Int64},P}}}()
    result = __normal_form_cached(p, data, cache, nothing, term_cache)
    return result.nf, result.multiplier, term_cache[p]
end

# Append the multiple subtracted in one exact or pseudo-reduction step.
# Keep the original equation and the admissible action shift so that the caller can reconstruct that prolongation.
function __normal_form_record_step!(
    terms::Vector{Tuple{P,Vector{Int64},P}},
    reduction,
    coefficient::P,
    exponent::Int,
) where {P<:ActionPolyRingElem}
    head_coefficient = (exponent == 0) ? coefficient : coefficient * reduction.variable^exponent
    push!(terms, (head_coefficient, collect(Int64, reduction.alpha), deepcopy(reduction.polynomial)))
    return terms
end

# Multiply all recorded identity coefficients by one polynomial in place.
# Preserve the equation and action shift associated with each coefficient.
function __normal_form_scale_terms!(terms::Vector{Tuple{P,Vector{Int64},P}}, c::P) where {P<:ActionPolyRingElem}
    __require_same_parent([(a, f) for (a, _, f) in terms], c)
    for i in eachindex(terms)
        terms[i] = (terms[i][1] * c, terms[i][2], terms[i][3])
    end
    return terms
end

function __normal_form_group_terms(
    terms::Vector{Tuple{P,Vector{Int64},P}},
    data::__ActionJanetData{P}
) where {P<:ActionPolyRingElem}
    R = __require_same_parent([(a, f) for (a, _, f) in terms], data.equations)
    grouped = Dict{Tuple{Tuple{Vararg{Int64}},P},P}()
    for (a, theta, f) in terms
        key = (Tuple(theta), f)
        grouped[key] = get(grouped, key, R(0)) + a
    end
    return [(a, collect(Int64, theta), f) for ((theta, f), a) in grouped if !is_zero(a)]
end

function __print_normal_form_terms(
    q::P,
    terms::AbstractVector{<:Tuple{P,Vector{Int64},P}},
    r::P,
) where {P<:ActionPolyRingElem}
    __require_same_parent(q, [(a, f) for (a, _, f) in terms], r)
    println("MULTIPLIER:")
    println(q)
    println("TERMS (COEFFICIENT, SHIFT, POLYNOMIAL):")
    for term in sort(collect(terms); by=string)
        println(term)
    end
    println("NORMAL_FORM:")
    println(r)
    return nothing
end
