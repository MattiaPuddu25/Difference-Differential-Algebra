@doc raw"""
    normal_form(
        p::P,
        F::AbstractVector{<:P}
    ) where {P<:ActionPolyRingElem}

Work in a difference or differential polynomial ring `R` with a fixed ranking.
Require `p` and the nonconstant equations `F` to have the same parent.
If `F` is Janet complete, return `(nf=r, multiplier=q)` with

    q*p - r ∈ [F],

where `[F]` is the difference or differential ideal generated by `F`.
The multiplier is a product of initials of the admissible prolongations used during pseudo-reduction.

Raise an error when `F` is not Janet complete.
For an empty vector, return `(nf=p, multiplier=one(p))`.

    # Examples

    ```jldoctest
    julia> R, (y2, y1) = difference_polynomial_ring(QQ, [:y2, :y1], 2; partition=[[1, 1]], index_ordering_name = :deglex);
    julia> p = y2[1,1]*y2[0,3]-y1[2,0];
    julia> f_1 = y1[0,1]^2+1;
    julia> f_2 = y1[2,0]+y2[0,1];
    julia> f_3 = y1[0,1]*y2[0,2];
    julia> f_4 = y1[1,1]^2-y1[1,0]^4;
    julia> F = [f_1, f_2, f_3, f_4];
    julia> p = y2[1,1]*y2[0,3]-y1[2,0];
    julia> normal_form(p, F)
    (nf = y2[0,1]*y1[0,2], multiplier = y1[0,2])

    julia> Qx, x = polynomial_ring(QQ, "x");
    julia> K, i = number_field(x^2 + 1, "i");
    julia> R, y = difference_polynomial_ring(K, :y, [action_shift(hom(K, K, -i))]);
    julia> f = y - i;
    julia> normal_form(apply_action(f, 1), [f])
    (nf = 0, multiplier = 1)

    julia> R, (y2, y1) = difference_polynomial_ring(QQ, [:y2, :y1], 1; partition=[[1,1]], index_ordering_name = :degrevlex);
    julia> f_1 = y1*y2[2];
    julia> f_2 = y2[2]^2-1;
    julia> F = [f_1,f_2];
    julia> p = y2^2;
    julia> normal_form(p,F)
    ERROR: The vector of action polynomials defining the equations must be Janet complete

    julia> R, u = differential_polynomial_ring(QQ, :u, 1);
    julia> du = u[1];
    julia> E = [du - u];
    julia> normal_form(u[2] - u, E)
    (nf = 0, multiplier = 1)
    ```

The derivative of a nonlinear equation is linear in its new leader:

    ```jldoctest
    julia> K, t = rational_function_field(QQ, "t");
    julia> R, u = differential_polynomial_ring(K, :u, [action_derivation(map_from_func(K, K, derivative))]);
    julia> f = u^2 - t;
    julia> normal_form(u[1], [f])
    (nf = 1, multiplier = 2*u[0])
    ```

The common multiplier is normalized at lower leaders when necessary:

    ```jldoctest
    julia> R, (v, u, a) = differential_polynomial_ring(QQ, [:v, :u, :a], 1);
    julia> w = v[2];
    julia> du = u[1];
    julia> E = [a^2 - 1, a*du - 1];
    julia> normal_form(du*(w^2 + w + 1), E)
    (nf = v[2]^2 + v[2] + 1, multiplier = a[0]^3)
    ```
"""
function normal_form(p::P, F::AbstractVector{<:P}) where {P<:ActionPolyRingElem}
    R = __require_same_parent(p, F)
    isempty(F) && return (nf=p+R(0), multiplier=R(1))
    return __normal_form(p, __normal_form_data(F))
end

function normal_form(p::ActionPolyRingElem, system::AbstractActionSystem)
    __require_parent(system.ring, p)
    return normal_form(p, system.equations)
end

"""
Internal recursive normal-form computation using the cached Janet data.\
The function repeatedly performs Janet-reduction with respect to the current leader while a univariate Janet reduction is available.
It then recursively reduces the coefficients of the remaining polynomial.

The input system is assumed to be Janet complete.
"""
function __normal_form(p::P, data::__ActionJanetData{P}) where {P<:ActionPolyRingElem}
    cache = Dict{P,Tuple{P,P}}()
    return __normal_form_cached(p, data, cache)
end

function __normal_form_data(equations::AbstractVector{<:P}) where {P<:ActionPolyRingElem}
    __require_same_parent(equations)
    equations = collect(P,equations)
    any(is_constant, equations) && error("The action polynomials defining the equations must be nonconstant")
    data = __action_janet_data(equations)
    __is_janet_complete(data) || error("The vector of action polynomials defining the equations must be Janet complete")
    return data
end

# Snapshot a zero normal form and the Janet cones that justify it.
# Keeping the equations alone is insufficient: inserting a new equation can
# turn an old multiplicative direction into a non-multiplicative one.
struct __NormalFormCertificate{P<:ActionPolyRingElem}
    nf::P
    multiplier::P
    basis::Vector{P}
    multiplicative_variables::Vector{BitVector}
end

function __NormalFormCertificate(
    nf::P,
    multiplier::P,
    data::__ActionJanetData{P}
 ) where {P<:ActionPolyRingElem}
    return __NormalFormCertificate(
        nf,
        multiplier,
        copy(data.equations),
        copy.(data.multiplicative_variables)
    )
end

function __normal_form_cached(
    p::P,
    data::__ActionJanetData{P},
    cache::Dict{P,Tuple{P,P}},
    certificate_cache::Union{Nothing,Dict{P,__NormalFormCertificate{P}}}=nothing,
    term_cache::Union{Nothing,Dict{P,Vector{Tuple{P,Vector{Int64},P}}}}=nothing
 ) where {P<:ActionPolyRingElem}
    cached = get(cache, p, nothing)
    if cached !== nothing && (term_cache === nothing || haskey(term_cache, p))
        return (nf=cached[1], multiplier=cached[2])
    end
    # Cross-basis zero certificates do not contain a complete reduction identity.
    if certificate_cache !== nothing && term_cache === nothing
        certified = __normal_form_certificate_lookup(p, data, certificate_cache)
        if certified !== nothing
            cache[p] = (certified.nf, certified.multiplier)
            return certified
        end
    end
    R = __require_same_parent(p, data.equations)
    remainder = p
    multiplier = R(1)
    terms = term_cache === nothing ? nothing : Tuple{P,Vector{Int64},P}[]
    while !is_constant(remainder)
        reduction = __is_janet_reducible_univariate_detailed(remainder, data)
        reduction === false && break
        v = reduction.variable
        reducer = reduction.prolongation
        reducer_degree, reducer_initial = __action_reduction_univariate_data(reduction, data)
        degree_difference = degree(Oscar.data(remainder), var_index(Oscar.data(v))) - reducer_degree
        remainder_initial = __action_univariate_initial(remainder, v)
        # Leader-linear reducers admit an exact cancellation whenever their initial divides the current initial.
        # Avoiding a pseudo-step here is useful for the differential Thomas queue:
        # repeated pseudo-multiplication otherwise would cause very large intermediate coefficients
        cancelled_initial = false
        if reducer_degree == 1
            division =
                if isone(reducer_initial)
                    (divides=true, quotient=remainder_initial)
                elseif is_constant(reducer_initial) && coefficient_ring(R) isa Field
                    (divides=true, quotient=divexact(remainder_initial, reducer_initial))
                else
                    __checked_divides(reducer_initial, remainder_initial)
                end
            if division.divides
                shifted_reducer = (degree_difference == 0) ? reducer : v^degree_difference * reducer
                remainder = remainder - division.quotient * shifted_reducer
                terms === nothing || __normal_form_record_step!(terms, reduction, division.quotient, degree_difference)
                cancelled_initial = true
            end
        end
        if !cancelled_initial
            multiplier *= reducer_initial
            shifted_reducer = (degree_difference == 0) ? reducer : v^degree_difference * reducer
            remainder = reducer_initial * remainder - remainder_initial * shifted_reducer
            if terms !== nothing
                isone(reducer_initial) || __normal_form_scale_terms!(terms, reducer_initial)
                __normal_form_record_step!(terms, reduction, remainder_initial, degree_difference)
            end
        end
    end
    if !is_constant(remainder)
        v = leader(remainder)
        coefficients = __action_univariate_coefficients_by_terms(remainder, v)
        reduced_remainder = R(0)
        coefficient_multiplier = R(1)
        for (degree_offset, coefficient) in enumerate(coefficients)
            is_zero(coefficient) && continue
            reduced_coefficient = __normal_form_coefficient_cached(coefficient, data, cache, certificate_cache, term_cache)
            exponent = degree_offset - 1
            coefficient_nf = reduced_coefficient.nf
            coefficient_factor = reduced_coefficient.multiplier
            # Avoid products by zero/one and powers v^0/v^1.
            # Scale the new term by the multipliers of previously processed coefficients.
            # Then include coefficient_factor in coefficient_multiplier.
            factor_is_one = isone(coefficient_factor)
            if terms !== nothing
                factor_is_one || __normal_form_scale_terms!(terms, coefficient_factor)
                coefficient_terms = term_cache[coefficient]
                if !isempty(coefficient_terms)
                    term_factor = exponent == 0 ? coefficient_multiplier : coefficient_multiplier * v^exponent
                    for (a, theta, f) in coefficient_terms
                        push!(terms, (isone(term_factor) ? a : term_factor*a, theta, f))
                    end
                end
            end
            if !factor_is_one && !is_zero(reduced_remainder)
                reduced_remainder = coefficient_factor * reduced_remainder
            end
            if !is_zero(coefficient_nf)
                shifted_nf =
                    if exponent == 0
                        coefficient_nf
                    elseif exponent == 1
                        coefficient_nf * v
                    else
                        coefficient_nf * v^exponent
                    end
                if !isone(coefficient_multiplier)
                    shifted_nf = coefficient_multiplier * shifted_nf
                end
                reduced_remainder = is_zero(reduced_remainder) ? shifted_nf : reduced_remainder + shifted_nf
            end
            if !factor_is_one
                coefficient_multiplier *= coefficient_factor
            end
        end
        remainder = reduced_remainder
        if !isone(coefficient_multiplier)
            multiplier *= coefficient_multiplier
        end
        # Products of coefficient multipliers can become reducible by an equation with
        # a strictly lower leader. Normalize once more only in that case;
        # every such recurrence descends in the ranking.
        if !is_constant(remainder) && __is_janet_reducible(remainder, data) !== false
            reduced_again = __normal_form_cached(remainder, data, cache, certificate_cache, term_cache)
            if terms !== nothing
                isone(reduced_again.multiplier) || __normal_form_scale_terms!(terms, reduced_again.multiplier)
                append!(terms, term_cache[remainder])
            end
            remainder = reduced_again.nf
            multiplier *= reduced_again.multiplier
        end
    end
    cache[p] = (remainder, multiplier)
    term_cache === nothing || (term_cache[p] = terms)
    # Keep persistent cross-basis certificates only for exact-zero normal forms
    if certificate_cache !== nothing && is_zero(remainder)
        certificate_cache[p] = __NormalFormCertificate(remainder, multiplier, data)
    end
    return (nf=remainder, multiplier=multiplier)
end

# Retrieve a saved zero result only if its equations remain available and none of their former multiplicative directions has been lost.
# Return nothing when the certificate cannot be reused.
# This is conservative because a particular computation may have used only some of those directions.
function __normal_form_certificate_lookup(
    p::P,
    data::__ActionJanetData{P},
    certificate_cache::Dict{P,__NormalFormCertificate{P}}
 ) where {P<:ActionPolyRingElem}
    certificate = get(certificate_cache, p, nothing)
    certificate === nothing && return nothing
    is_zero(certificate.nf) || return nothing
    for (f, old_mask) in zip(certificate.basis, certificate.multiplicative_variables)
        index = get(data.indices, f, 0)
        iszero(index) && return nothing
        new_mask = data.multiplicative_variables[index]
        for i in eachindex(old_mask, new_mask)
            old_mask[i] && !new_mask[i] && return nothing
        end
    end
    return (nf=certificate.nf, multiplier=certificate.multiplier)
end

