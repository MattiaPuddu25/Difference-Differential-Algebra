@doc raw"""
    solution_check(
        r::MPolyRingElem{T},
        E::AbstractVector{<:MPolyRingElem{T}}
    ) where T
    solution_check(
        r::MPolyRingElem{T},
        E::AbstractVector{<:MPolyRingElem{T}},
        I::AbstractVector{<:MPolyRingElem{T}}
    ) where T

Given a polynomial `r` and a vector of polynomials `E` (in the same polynomial ring over a field K, with a fixed ordering of the variables),
    return `true` if the system

    `r` = 0,\
    f = 0 for f in `E` with leader(f) <= leader(`r`)

has solutions in a fixed algebraic closure of K, and `false` otherwise.

With the third input `I`, also impose

    q ≠ 0 for q in `I` with leader(q) <= leader(`r`).

The function uses Hilbert Nullstellensatz.
In the equation-only case it checks whether the equation ideal is the whole ring; in the equation-and-inequation
    case it checks radical membership of the product of the relevant inequations.

# Examples

```jldoctest
julia> R, (x1, x2, x3) = polynomial_ring(QQ, [:x1, :x2, :x3])
julia> r = x2^2+1;
julia> E = [x1^2+x2^2-1, x3^2-x1];
julia> solution_check(r, E)
true


julia> R, (x1, x2, x3) = polynomial_ring(QQ, [:x1, :x2, :x3])
julia> r = x2^2-1;
julia> E = [x2^2-2];
julia> solution_check(r, E)
false


julia> R, (x1, x2) = polynomial_ring(QQ, [:x1, :x2])
julia> r = x2*x1;
julia> E = [x2];
julia> I = [x2];
julia> solution_check(r, E, I)
false


julia> R, (x1, x2, x3) = polynomial_ring(QQ, [:x1, :x2, :x3])
julia> r = x2^2-1;
julia> E = [x1^3*x2+x1];
julia> I = [x1+x2, x1^2];
julia> solution_check(r, E, I)
true


julia> R, (x1, x2, x3) = polynomial_ring(QQ, [:x1, :x2, :x3])
julia> r = x2^2;
julia> E = [x2^3*x3+x2];
julia> I = [x2+x3, x2^2];
julia> solution_check(r, E, I)
false


julia> R, (x4, x1, x2, x3) = polynomial_ring(QQ, [:x4, :x1, :x2, :x3])
julia> r = x1^2-x1*x2-x1*x3-5;
julia> E = [x2^2-x2*x3-x1*x2+4, x3^2-x1*x3-x2*x3+7];
