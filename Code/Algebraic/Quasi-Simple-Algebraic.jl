@doc raw"""
    is_quasi_simple(
        E::AbstractVector{<:MPolyRingElem{T}};
        info::Bool=false
    ) where T
    is_quasi_simple(
        E::AbstractVector{<:MPolyRingElem{T}},
        I::AbstractVector{<:MPolyRingElem{T}};
        info::Bool=false
    ) where T

Given a vector of polynomials `E` (all in the same polynomial ring over a field K, with a fixed ordering of the variables),
    return `true` if the system of polynomial equations

    f = 0 for f in `E`

is quasi-simple as an algebraic system, and `false` otherwise.

With the second input `I`, also include the inequations

    q ≠ 0 for q in `I`.

to the system.\
In the second case, if the optional argument info is set to `true` (which is not its default value),
    a message explaining the first problem encountered is printed.

# Examples

```jldoctest
julia> R, (x3, x2, x1) = polynomial_ring(QQ, [:x3, :x2, :x1])
julia> E = [x1^2+x2^2-1, x3^2-x1];
julia> is_quasi_simple(E)
true


julia> R, (x3, x2, x1) = polynomial_ring(QQ, [:x3, :x2, :x1])
julia> E = [x1^2*x3-1, x1*x2^2+x2];
julia> is_quasi_simple(E)
false


julia> R, (x3, x2, x1) = polynomial_ring(QQ, [:x3, :x2, :x1])
julia> E = [3*x1^2*x2-5*x3+2, -x1^3+7*x2^2*x3+4, x1*x2-9*x3^2+x1];
julia> is_quasi_simple(E; info=true)
There are polynomials with the same leader
false


julia> R, (x1, x2, x3, x4, x5) = polynomial_ring(QQ, [:x1, :x2, :x3, :x4, :x5])
julia> E = [(x5+1)*x1^2+x2-x3, (x4+x5-1)*x2^2+x3-x5, (x3+x4*x5-1)*x3^2+x4^2-x5];
julia> I = [x5*x4^2-1];
julia> is_quasi_simple(E;info=true)
The initial of Equation 1 has solutions in the corresponding subsystem
false


julia> R, (x3, x2, x1) = polynomial_ring(QQ, [:x3, :x2, :x1])
julia> E = [x1^2*x3-1, x1*x2^2+x2];
julia> I = [x1];
julia> is_quasi_simple(E, I)
true


julia> R, (x3, x2, x1) = polynomial_ring(QQ, [:x3, :x2, :x1])
julia> E = [3*x1^2*x2-5*x3+2, -x1^3+7*x2^2+4];
julia> I = [x1^2-1];
julia> is_quasi_simple(E, I)
true


julia> R, (x1, x2, x3, x4, x5) = polynomial_ring(QQ, [:x1, :x2, :x3, :x4, :x5])
julia> E = [(x5+1)*x1^2+x2-x3, (x4+x5-1)*x2^2+x3-x5, (x3+x4*x5-1)*x3^2+x4^2-x5];
julia> I = [x5+1];
julia> is_quasi_simple(E, I; info=true)
The initial of Equation 2 has solutions in the corresponding subsystem
false
```
"""
function is_quasi_simple(
    E::AbstractVector{<:MPolyRingElem{T}};
    info::Bool=false
) where T
    # No constant polynomials
    for p in E
        if is_constant(p)
            if info == true
                println("There are constant polynomials")
            end
            return false
        end
    end
    # Pairwise distinct leaders
    s = length(E)
    E_leaders = [poly_leader(p) for p in E]
    S = Set(E_leaders)
    if length(S) < s
        if info == true
            println("There are polynomials with the same leader")
        end
        return false
    end
    # No solutions in appropriate subsystems
    for (i, r) in enumerate(E)
        if __solution_check(poly_initial(r), E, E_leaders)
            if info == true
                println("The initial of Equation $i has solutions in the corresponding subsystem")
            end
            return false
        end
    end
    return true
end

function is_quasi_simple(
    E::AbstractVector{<:MPolyRingElem{T}},
    I::AbstractVector{<:MPolyRingElem{T}};
    info::Bool=false
) where T
    all_polys = [E; I]
    # No constant polynomials
    for p in all_polys
        if is_constant(p)
            if info == true
                println("There are constant polynomials")
            end
            return false
        end
    end
    # Pairwise distinct leaders
    s = length(E)
    t = length(I)
    E_leaders = [poly_leader(p) for p in E]
    I_leaders = [poly_leader(q) for q in I]
    S = Set(E_leaders)
    S_i = Set(I_leaders)
    U = union(S, S_i)
    if length(U) < s + t
        if info == true
            println("There are polynomials with the same leader")
        end
        return false
    end
    # No solutions in appropriate subsystems
    for (i, r) in enumerate(all_polys)
        if __solution_check(poly_initial(r), E, E_leaders, I, I_leaders)
            if info == true && i <= length(E)
                println("The initial of Equation $i has solutions in the corresponding subsystem")
            end
            if info == true && i > length(E)
                println("The initial of Inequation $(i - length(E)) has solutions in the corresponding subsystem")
            end
            return false
        end
    end
    return true
end

