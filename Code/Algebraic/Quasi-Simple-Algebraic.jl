@doc raw"""
    __leader_filter(
        V::AbstractVector{<:MPolyRingElem{T}},
        leaders,
        p::MPolyRingElem{T}
    ) where T

Internal version of leader\_filter using supplied leaders.

Return the unique polynomials in `V` whose supplied leader is less than or equal to poly\_leader(p).
When the leaders are precomputed, this avoids recomputing the leaders of the same equation and inequation lists
    during quasi-simplicity checks.
"""
function __leader_filter(
    V::AbstractVector{<:MPolyRingElem{T}},
    leaders,
    p::MPolyRingElem{T}
) where T
    ld = poly_leader(p)
    S = [f for (f, f_leader) in zip(V, leaders) if f_leader <= ld]
    return unique!(S)
end

@doc raw"""
    __algebraic_product(R::Ring, V::AbstractVector)

Return the product of the entries of `V`, using `R(1)` as the empty product.
"""
function __algebraic_product(R::Ring, V::AbstractVector)
    q = R(1)
    for p in V
        q *= p
    end
    return q
end

@doc raw"""
    __compatible_zero_algebraic_system(
        r::MPolyRingElem{T},
        E::AbstractVector{<:MPolyRingElem{T}},
        I::AbstractVector{<:MPolyRingElem{T}}
    ) where T
    __compatible_zero_algebraic_system(
        r::MPolyRingElem{T},
        E::AbstractVector{<:MPolyRingElem{T}}
    ) where T

Return `true` if `r = 0` has a solution compatible with `E = 0` and `I != 0`.

Computationally, this tests whether the product of the inequations is not in the radical of the ideal
    generated by `E` and `r`.
With no inequations, it only tests whether that ideal is proper.
"""
function __compatible_zero_algebraic_system(
    r::MPolyRingElem{T},
    E::AbstractVector{<:MPolyRingElem{T}},
    I::AbstractVector{<:MPolyRingElem{T}},
) where T
    is_constant(r) && !is_zero(r) && return false

    R = parent(r)
    Eq = collect(E)
    push!(Eq, r)
    unique!(Eq)

    J = ideal(R, Eq)
    is_one(J) && return false

    I = collect(I)
    isempty(I) && return true
    Q = __algebraic_product(R, I)
    return !radical_membership(Q, J)
end

function __compatible_zero_algebraic_system(
    r::MPolyRingElem{T},
    E::AbstractVector{<:MPolyRingElem{T}},
) where T
    return __compatible_zero_algebraic_system(r, E, typeof(r)[])
end

@doc raw"""
    __checked_divides(a, b)

Return a named tuple with fields `divides` and `quotient`.

The field `divides` is `true` exactly when `a*q == b` for the returned
`quotient`; otherwise `divides` is `false` and `quotient` is `nothing`.

"""
function __checked_divides(a, b)
    try
        d = Oscar.divides(a, b)
        d[1] && return (divides=true, quotient=d[2])
    catch
    end
    try
        q = divexact(b, a)
        a * q == b && return (divides=true, quotient=q)
    catch
    end
    return (divides=false, quotient=nothing)
end

@doc raw"""
    __regular_in_localized_algebraic_system(
        p::MPolyRingElem{T},
        E::AbstractVector{<:MPolyRingElem{T}},
        I::AbstractVector{<:MPolyRingElem{T}},
    ) where T

Return `true` if the class of `p` is regular in the localization of the
    coordinate ring defined by `E = 0` at the product of the guards `I`.

Equivalently, if `J = ideal(E)` and `S = prod(I)`, this checks whether
    `(J : S^∞) : p^∞ = J : S^∞`.
"""
function __regular_in_localized_algebraic_system(
    p::MPolyRingElem{T},
    E::AbstractVector{<:MPolyRingElem{T}},
    I::AbstractVector{<:MPolyRingElem{T}},
) where T
    is_zero(p) && return false
    is_constant(p) && return true

    R = parent(p)
    E = collect(E)
    I = collect(I)
    J = ideal(R, E)
    is_one(J) && return true

    K = J
    if !isempty(I)
        q = __algebraic_product(R, I)
        is_zero(q) && return true
        K = saturation(J, ideal(R, [q]))
        is_one(K) && return true
    end

    Kp = saturation(K, ideal(R, [p]))
    return Kp == K
end

@doc raw"""
    __solution_check(
        r::MPolyRingElem{T},
        E::AbstractVector{<:MPolyRingElem{T}},
        E_leaders::AbstractVector
    ) where T
    __solution_check(
        r::MPolyRingElem{T},
        E::AbstractVector{<:MPolyRingElem{T}},
        E_leaders::AbstractVector,
        I::AbstractVector{<:MPolyRingElem{T}},
        I_leaders::AbstractVector,
    ) where T

Internal solution check using precomputed leaders.

The first method tests whether the algebraic system consisting of `r` = 0 and
    the relevant equations from `E` has a solution in a fixed algebraic closure.
The second method also imposes the relevant inequations from `I`.
Relevant means that the corresponding precomputed leader is less than or equal to the leader of `r`.
"""
function __solution_check(
    r::MPolyRingElem{T},
    E::AbstractVector{<:MPolyRingElem{T}},
    E_leaders::AbstractVector
) where T
    S = __leader_filter(E, E_leaders, r)
    return __compatible_zero_algebraic_system(r, S)
end


function __solution_check(
    r::MPolyRingElem{T},
    E::AbstractVector{<:MPolyRingElem{T}},
    E_leaders::AbstractVector,
    I::AbstractVector{<:MPolyRingElem{T}},
    I_leaders::AbstractVector,
) where T
    Eq = __leader_filter(E, E_leaders, r)
    Ineq = __leader_filter(I, I_leaders, r)
    return __compatible_zero_algebraic_system(r, Eq, Ineq)
end

@doc raw"""
    __solution_check_ineq(
        r::MPolyRingElem{T},
        I::AbstractVector{<:MPolyRingElem{T}},
        I_leaders::AbstractVector
    ) where T

Internal inequation-only solution check using precomputed inequation leaders.

It tests whether `r` = 0 is compatible with the relevant inequations from `I`.
The relevant inequations are those whose precomputed leader is less than or equal to poly\_leader(r).
"""
function __solution_check_ineq(
    r::MPolyRingElem{T},
    I::AbstractVector{<:MPolyRingElem{T}},
    I_leaders::AbstractVector
) where T
    Ineq = __leader_filter(I, I_leaders, r)
    return __compatible_zero_algebraic_system(r, typeof(r)[], Ineq)
end

